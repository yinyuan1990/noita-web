// 临时探针:地表外观对照。开局落地后截图,再往左/右走一段各截一张(远山视差 / 树 / 中景背景)
import { chromium } from 'playwright'
const out = process.argv[2] || 'C:/Users/admin/AppData/Local/Temp'
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const ctx = await browser.newContext({ viewport: { width: 854, height: 480 }, deviceScaleFactor: 1 })
const page = await ctx.newPage()
page.on('pageerror', (e) => console.log('PAGEERROR', e.message))
page.on('console', (m) => { if (m.type() === 'error' && !/404/.test(m.text())) console.log('CONSOLE', m.text()) })
await page.goto('http://localhost:5177/noita-play.html?log=0' + (process.argv[3] ? '&' + process.argv[3] : ''))
await page.waitForFunction(() => window.__np && window.__np.streamer.entries.size > 0, null, { timeout: 60000 })
await page.waitForTimeout(3000)
console.log('落地', await page.evaluate(() => ({ x: window.__np.player.x | 0, y: window.__np.player.y | 0, cam: [window.__np.cam.x | 0, window.__np.cam.y | 0] })))
await page.screenshot({ path: `${out}/surface-0.png` })
await page.keyboard.down('a'); await page.waitForTimeout(3500); await page.keyboard.up('a'); await page.waitForTimeout(800)
console.log('左', await page.evaluate(() => ({ x: window.__np.player.x | 0, y: window.__np.player.y | 0 })))
await page.screenshot({ path: `${out}/surface-left.png` })
await page.keyboard.down('d'); await page.waitForTimeout(7000); await page.keyboard.up('d'); await page.waitForTimeout(800)
console.log('右', await page.evaluate(() => ({ x: window.__np.player.x | 0, y: window.__np.player.y | 0 })))
await page.screenshot({ path: `${out}/surface-right.png` })
console.log(await page.evaluate(() => document.getElementById('panel').textContent.replace(/\n/g, ' | ')))
await browser.close()
